FROM HEALTHCARE_DB.BRONZE.DEPARTMENTS_MU
WHERE DEPARTMENT_ID IS NOT NULL;

-- PATIENTS_MU (all VARCHAR -> cast IDs, dates, booleans)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.PATIENTS_MU AS
SELECT
    CAST(PATIENT_ID AS NUMBER(38,0)) AS PATIENT_ID,
    TRIM(PATIENT_CODE) AS PATIENT_CODE,
    TRIM(MEDICAID_ID) AS MEDICAID_ID,
    TRIM(MEDICARE_ID) AS MEDICARE_ID,
    TRIM(SSN_LAST4) AS SSN_LAST4,
    TRIM(INITCAP(FIRST_NAME)) AS FIRST_NAME,
    TRIM(INITCAP(MIDDLE_NAME)) AS MIDDLE_NAME,
    TRIM(INITCAP(LAST_NAME)) AS LAST_NAME,
    TRIM(INITCAP(FIRST_NAME)) || COALESCE(' ' || TRIM(INITCAP(MIDDLE_NAME)), '') || ' ' || TRIM(INITCAP(LAST_NAME)) AS FULL_NAME,
    TRIM(INITCAP(GENDER)) AS GENDER,
    TRY_CAST(DATE_OF_BIRTH AS DATE) AS DATE_OF_BIRTH,
    TRY_CAST(DATE_OF_DEATH AS DATE) AS DATE_OF_DEATH,
    TRIM(INITCAP(MARITAL_STATUS)) AS MARITAL_STATUS,
    TRIM(INITCAP(PREFERRED_LANGUAGE)) AS PREFERRED_LANGUAGE,
    TRIM(INITCAP(RACE)) AS RACE,
    TRIM(INITCAP(ETHNICITY)) AS ETHNICITY,
    TRIM(INITCAP(CITIZENSHIP_STATUS)) AS CITIZENSHIP_STATUS,
    TRIM(PHONE_HOME) AS PHONE_HOME,
    TRIM(PHONE_MOBILE) AS PHONE_MOBILE,
    TRIM(LOWER(EMAIL)) AS EMAIL,
    TRIM(INITCAP(ADDRESS_LINE1)) AS ADDRESS_LINE1,
    TRIM(INITCAP(ADDRESS_LINE2)) AS ADDRESS_LINE2,
    TRIM(INITCAP(CITY)) AS CITY,
    TRIM(INITCAP(COUNTY)) AS COUNTY,
    TRIM(UPPER(STATE)) AS STATE,
    TRIM(ZIP_CODE) AS ZIP_CODE,
    COALESCE(TRIM(UPPER(COUNTRY)), 'USA') AS COUNTRY,
    TRIM(INITCAP(HOUSING_STATUS)) AS HOUSING_STATUS,
    TRIM(INITCAP(VETERAN_STATUS)) AS VETERAN_STATUS,
    TRIM(INITCAP(DISABILITY_STATUS)) AS DISABILITY_STATUS,
    CASE LOWER(TRIM(DECEASED_FLAG)) WHEN 'true' THEN TRUE WHEN '1' THEN TRUE ELSE FALSE END AS DECEASED_FLAG,
    TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
    TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT
FROM HEALTHCARE_DB.BRONZE.PATIENTS_MU
WHERE PATIENT_ID IS NOT NULL;

-- ENCOUNTERS_MU (all VARCHAR -> cast + dedup)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.ENCOUNTERS_MU AS
SELECT * EXCLUDE (RN) FROM (
    SELECT
        CAST(ENCOUNTER_ID AS NUMBER(38,0)) AS ENCOUNTER_ID,
        CAST(APPOINTMENT_ID AS NUMBER(38,0)) AS APPOINTMENT_ID,
        CAST(PATIENT_ID AS NUMBER(38,0)) AS PATIENT_ID,
        CAST(DOCTOR_ID AS NUMBER(38,0)) AS DOCTOR_ID,
        CAST(PROVIDER_ID AS NUMBER(38,0)) AS PROVIDER_ID,
        TRIM(ENCOUNTER_NUMBER) AS ENCOUNTER_NUMBER,
        TRY_CAST(ENCOUNTER_DATE AS DATE) AS ENCOUNTER_DATE,
        TRIM(INITCAP(ENCOUNTER_TYPE)) AS ENCOUNTER_TYPE,
        TRIM(INITCAP(PLACE_OF_SERVICE)) AS PLACE_OF_SERVICE,
        TRIM(INITCAP(ADMIT_SOURCE)) AS ADMIT_SOURCE,
        TRIM(INITCAP(DISCHARGE_STATUS)) AS DISCHARGE_STATUS,
        TRIM(CHIEF_COMPLAINT) AS CHIEF_COMPLAINT,
        TRIM(DIAGNOSIS_SUMMARY) AS DIAGNOSIS_SUMMARY,
        TRIM(CLINICAL_NOTES) AS CLINICAL_NOTES,
        CASE LOWER(TRIM(FOLLOWUP_REQUIRED_FLAG)) WHEN 'true' THEN TRUE WHEN '1' THEN TRUE ELSE FALSE END AS FOLLOWUP_REQUIRED_FLAG,
        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        ROW_NUMBER() OVER (PARTITION BY ENCOUNTER_ID ORDER BY CREATED_AT DESC) AS RN
    FROM HEALTHCARE_DB.BRONZE.ENCOUNTERS_MU
    WHERE PATIENT_ID IS NOT NULL AND PROVIDER_ID IS NOT NULL AND ENCOUNTER_DATE IS NOT NULL
) WHERE RN = 1;

-- CLAIMS_MU (all VARCHAR -> cast + dedup + null defaults)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.CLAIMS_MU AS
SELECT * EXCLUDE (RN) FROM (
    SELECT
        CAST(CLAIM_ID AS NUMBER(38,0)) AS CLAIM_ID,
        TRIM(CLAIM_NUMBER) AS CLAIM_NUMBER,
        CAST(PATIENT_ID AS NUMBER(38,0)) AS PATIENT_ID,
        CAST(PROVIDER_ID AS NUMBER(38,0)) AS PROVIDER_ID,
        CAST(DOCTOR_ID AS NUMBER(38,0)) AS DOCTOR_ID,
        CAST(PAYER_ID AS NUMBER(38,0)) AS PAYER_ID,
        CAST(PLAN_ID AS NUMBER(38,0)) AS PLAN_ID,
        CAST(ENCOUNTER_ID AS NUMBER(38,0)) AS ENCOUNTER_ID,
        TRIM(INITCAP(CLAIM_TYPE)) AS CLAIM_TYPE,
        TRIM(INITCAP(CLAIM_STATUS)) AS CLAIM_STATUS,
        TRY_CAST(CLAIM_RECEIVED_DATE AS DATE) AS CLAIM_RECEIVED_DATE,
        TRY_CAST(SERVICE_FROM_DATE AS DATE) AS SERVICE_FROM_DATE,
        TRY_CAST(SERVICE_TO_DATE AS DATE) AS SERVICE_TO_DATE,
        TRIM(UPPER(BILL_TYPE)) AS BILL_TYPE,
        TRIM(INITCAP(PLACE_OF_SERVICE)) AS PLACE_OF_SERVICE,
        TRIM(UPPER(DIAGNOSIS_RELATED_GROUP)) AS DIAGNOSIS_RELATED_GROUP,
        COALESCE(TRY_CAST(TOTAL_BILLED_AMOUNT AS FLOAT), 0) AS TOTAL_BILLED_AMOUNT,
        COALESCE(TRY_CAST(TOTAL_ALLOWED_AMOUNT AS FLOAT), 0) AS TOTAL_ALLOWED_AMOUNT,
        COALESCE(TRY_CAST(TOTAL_PAID_AMOUNT AS FLOAT), 0) AS TOTAL_PAID_AMOUNT,
        COALESCE(TRY_CAST(PATIENT_RESPONSIBILITY_AMOUNT AS FLOAT), 0) AS PATIENT_RESPONSIBILITY_AMOUNT,
        TRIM(DENIAL_REASON) AS DENIAL_REASON,
        CASE LOWER(TRIM(ADJUSTED_FLAG)) WHEN 'true' THEN TRUE WHEN '1' THEN TRUE ELSE FALSE END AS ADJUSTED_FLAG,
        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY CREATED_AT DESC) AS RN
    FROM HEALTHCARE_DB.BRONZE.CLAIMS_MU
    WHERE PATIENT_ID IS NOT NULL AND PROVIDER_ID IS NOT NULL
) WHERE RN = 1;

-- CLAIM_LINES_MU (all VARCHAR -> cast + null defaults)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.CLAIM_LINES_MU AS
SELECT * EXCLUDE (RN) FROM (
    SELECT
        CAST(CLAIM_LINE_ID AS NUMBER(38,0)) AS CLAIM_LINE_ID,
        CAST(CLAIM_ID AS NUMBER(38,0)) AS CLAIM_ID,
        CAST(LINE_NUMBER AS NUMBER(38,0)) AS LINE_NUMBER,
        CAST(PROCEDURE_ID AS NUMBER(38,0)) AS PROCEDURE_ID,
        TRIM(DIAGNOSIS_POINTER) AS DIAGNOSIS_POINTER,
        TRIM(UPPER(REVENUE_CODE)) AS REVENUE_CODE,
        TRIM(UPPER(HCPCS_CODE)) AS HCPCS_CODE,
        TRIM(UPPER(MODIFIER_1)) AS MODIFIER_1,
        TRIM(UPPER(MODIFIER_2)) AS MODIFIER_2,
        COALESCE(TRY_CAST(UNITS AS NUMBER(38,0)), 0) AS UNITS,
        COALESCE(TRY_CAST(LINE_BILLED_AMOUNT AS FLOAT), 0) AS LINE_BILLED_AMOUNT,
        COALESCE(TRY_CAST(LINE_ALLOWED_AMOUNT AS FLOAT), 0) AS LINE_ALLOWED_AMOUNT,
        COALESCE(TRY_CAST(LINE_PAID_AMOUNT AS FLOAT), 0) AS LINE_PAID_AMOUNT,
        TRIM(LINE_DENIAL_REASON) AS LINE_DENIAL_REASON,
        TRY_CAST(SERVICE_DATE AS DATE) AS SERVICE_DATE,
        ROW_NUMBER() OVER (PARTITION BY CLAIM_LINE_ID ORDER BY SERVICE_DATE DESC) AS RN
    FROM HEALTHCARE_DB.BRONZE.CLAIM_LINES_MU
    WHERE CLAIM_LINE_ID IS NOT NULL AND CLAIM_ID IS NOT NULL
) WHERE RN = 1;

-- PRIOR_AUTHORIZATIONS_MU (all VARCHAR -> cast + dedup)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.PRIOR_AUTHORIZATIONS_MU AS
SELECT * EXCLUDE (RN) FROM (
    SELECT
        CAST(PRIOR_AUTH_ID AS NUMBER(38,0)) AS PRIOR_AUTH_ID,
        TRIM(AUTH_NUMBER) AS AUTH_NUMBER,
        CAST(PATIENT_ID AS NUMBER(38,0)) AS PATIENT_ID,
        CAST(PROVIDER_ID AS NUMBER(38,0)) AS PROVIDER_ID,
        CAST(DOCTOR_ID AS NUMBER(38,0)) AS DOCTOR_ID,
        CAST(PAYER_ID AS NUMBER(38,0)) AS PAYER_ID,
        CAST(PLAN_ID AS NUMBER(38,0)) AS PLAN_ID,
        TRY_CAST(REQUEST_DATE AS DATE) AS REQUEST_DATE,
        TRY_CAST(DECISION_DATE AS DATE) AS DECISION_DATE,
        TRIM(INITCAP(SERVICE_TYPE)) AS SERVICE_TYPE,
        CAST(PROCEDURE_ID AS NUMBER(38,0)) AS PROCEDURE_ID,
        COALESCE(TRY_CAST(REQUESTED_UNITS AS NUMBER(38,0)), 0) AS REQUESTED_UNITS,
        COALESCE(TRY_CAST(APPROVED_UNITS AS NUMBER(38,0)), 0) AS APPROVED_UNITS,
        TRIM(INITCAP(AUTH_STATUS)) AS AUTH_STATUS,
        TRIM(DENIAL_REASON) AS DENIAL_REASON,
        TRY_CAST(VALID_FROM AS DATE) AS VALID_FROM,
        TRY_CAST(VALID_TO AS DATE) AS VALID_TO,
        CASE LOWER(TRIM(URGENT_FLAG)) WHEN 'true' THEN TRUE WHEN '1' THEN TRUE ELSE FALSE END AS URGENT_FLAG,
