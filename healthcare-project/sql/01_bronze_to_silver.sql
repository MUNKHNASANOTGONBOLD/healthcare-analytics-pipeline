-- =====================================================
-- SECTION 1: BRONZE -> SILVER (clean + type cast + dedup + standardize)
-- =====================================================

-- REFERENCE_CODES_MU (all VARCHAR -> cast)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU AS
SELECT
    CAST(REF_ID AS NUMBER(38,0)) AS REF_ID,
    TRIM(UPPER(REF_DOMAIN)) AS REF_DOMAIN,
    TRIM(UPPER(REF_CODE)) AS REF_CODE,
    TRIM(INITCAP(REF_DESCRIPTION)) AS REF_DESCRIPTION,
    CASE LOWER(TRIM(ACTIVE_FLAG)) WHEN 'true' THEN TRUE WHEN '1' THEN TRUE ELSE FALSE END AS ACTIVE_FLAG
FROM HEALTHCARE_DB.BRONZE.REFERENCE_CODES_MU
WHERE REF_ID IS NOT NULL;

-- PROVIDERS_MU (lowercase cols, mixed types)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.PROVIDERS_MU AS
SELECT
    "provider_id" AS PROVIDER_ID,
    TRIM("provider_code") AS PROVIDER_CODE,
    TRIM(UPPER("npi")) AS NPI,
    TRIM(UPPER("taxonomy_code")) AS TAXONOMY_CODE,
    TRIM(INITCAP("provider_name")) AS PROVIDER_NAME,
    TRIM(INITCAP("legal_name")) AS LEGAL_NAME,
    TRIM(INITCAP("provider_type")) AS PROVIDER_TYPE,
    TRIM(INITCAP("specialty")) AS SPECIALTY,
    TRIM(INITCAP("sub_specialty")) AS SUB_SPECIALTY,
    TRIM("tin") AS TIN,
    TRIM("medicaid_provider_id") AS MEDICAID_PROVIDER_ID,
    TRIM("medicare_provider_id") AS MEDICARE_PROVIDER_ID,
    TRIM("phone") AS PHONE,
    TRIM("fax") AS FAX,
    TRIM(LOWER("email")) AS EMAIL,
    TRIM("website") AS WEBSITE,
    TRIM(INITCAP("address_line1")) AS ADDRESS_LINE1,
    TRIM(INITCAP("address_line2")) AS ADDRESS_LINE2,
    TRIM(INITCAP("city")) AS CITY,
    TRIM(INITCAP("county")) AS COUNTY,
    TRIM(UPPER("state")) AS STATE,
    TRIM("zip_code") AS ZIP_CODE,
    COALESCE(TRIM(UPPER("country")), 'USA') AS COUNTRY,
    TRIM(INITCAP("network_status")) AS NETWORK_STATUS,
    COALESCE("active_flag", TRUE) AS ACTIVE_FLAG,
    "effective_date" AS EFFECTIVE_DATE,
    "termination_date" AS TERMINATION_DATE,
    "created_at" AS CREATED_AT,
    "updated_at" AS UPDATED_AT
FROM HEALTHCARE_DB.BRONZE.PROVIDERS_MU
WHERE "provider_id" IS NOT NULL;

-- DEPARTMENTS_MU (all VARCHAR)
CREATE OR REPLACE TABLE HEALTHCARE_DB.SILVER.DEPARTMENTS_MU AS
SELECT
    CAST(DEPARTMENT_ID AS NUMBER(38,0)) AS DEPARTMENT_ID,
    TRIM(UPPER(DEPARTMENT_CODE)) AS DEPARTMENT_CODE,
    TRIM(INITCAP(DEPARTMENT_NAME)) AS DEPARTMENT_NAME,
    TRIM(INITCAP(DEPARTMENT_TYPE)) AS DEPARTMENT_TYPE,
    TRIM(INITCAP(LOCATION)) AS LOCATION,
    TRIM(UPPER(COST_CENTER)) AS COST_CENTER,
