-- =====================================================
-- SECTION 2: DATA STANDARDIZATION (via REFERENCE_CODES in Silver)
-- =====================================================

-- CLAIMS: standardize CLAIM_STATUS
UPDATE HEALTHCARE_DB.SILVER.CLAIMS_MU C
SET C.CLAIM_STATUS = RC.REF_DESCRIPTION
FROM HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU RC
WHERE RC.REF_DOMAIN = 'CLAIM_STATUS'
  AND RC.REF_CODE = UPPER(REPLACE(C.CLAIM_STATUS, ' ', '_'))
  AND RC.ACTIVE_FLAG = TRUE;

-- PRIOR_AUTHORIZATIONS: standardize AUTH_STATUS
UPDATE HEALTHCARE_DB.SILVER.PRIOR_AUTHORIZATIONS_MU PA
SET PA.AUTH_STATUS = RC.REF_DESCRIPTION
FROM HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU RC
WHERE RC.REF_DOMAIN = 'AUTH_STATUS'
  AND RC.REF_CODE = UPPER(REPLACE(PA.AUTH_STATUS, ' ', '_'))
  AND RC.ACTIVE_FLAG = TRUE;

-- APPOINTMENTS: standardize APPOINTMENT_STATUS
UPDATE HEALTHCARE_DB.SILVER.APPOINTMENTS_MU A
SET A.APPOINTMENT_STATUS = RC.REF_DESCRIPTION
FROM HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU RC
WHERE RC.REF_DOMAIN = 'APPOINTMENT_STATUS'
  AND RC.REF_CODE = UPPER(REPLACE(A.APPOINTMENT_STATUS, ' ', '_'))
  AND RC.ACTIVE_FLAG = TRUE;

-- PATIENTS: standardize GENDER
UPDATE HEALTHCARE_DB.SILVER.PATIENTS_MU P
SET P.GENDER = RC.REF_DESCRIPTION
FROM HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU RC
WHERE RC.REF_DOMAIN = 'GENDER'
  AND RC.REF_CODE = UPPER(REPLACE(P.GENDER, ' ', '_'))
  AND RC.ACTIVE_FLAG = TRUE;

-- =====================================================
-- SECTION 3: VALIDATION
-- =====================================================

-- Row counts across every Silver table
SELECT 'PATIENTS' AS TBL, COUNT(*) AS ROW_CNT FROM HEALTHCARE_DB.SILVER.PATIENTS_MU
UNION ALL SELECT 'PROVIDERS', COUNT(*) FROM HEALTHCARE_DB.SILVER.PROVIDERS_MU
UNION ALL SELECT 'DEPARTMENTS', COUNT(*) FROM HEALTHCARE_DB.SILVER.DEPARTMENTS_MU
UNION ALL SELECT 'ENCOUNTERS', COUNT(*) FROM HEALTHCARE_DB.SILVER.ENCOUNTERS_MU
UNION ALL SELECT 'CLAIMS', COUNT(*) FROM HEALTHCARE_DB.SILVER.CLAIMS_MU
UNION ALL SELECT 'CLAIM_LINES', COUNT(*) FROM HEALTHCARE_DB.SILVER.CLAIM_LINES_MU
UNION ALL SELECT 'PRIOR_AUTH', COUNT(*) FROM HEALTHCARE_DB.SILVER.PRIOR_AUTHORIZATIONS_MU
UNION ALL SELECT 'APPOINTMENTS', COUNT(*) FROM HEALTHCARE_DB.SILVER.APPOINTMENTS_MU
UNION ALL SELECT 'REFERENCE_CODES', COUNT(*) FROM HEALTHCARE_DB.SILVER.REFERENCE_CODES_MU
ORDER BY TBL;

-- Verify standardized values
SELECT 'CLAIM_STATUS' AS DOMAIN, CLAIM_STATUS AS VALUE, COUNT(*) AS CNT FROM HEALTHCARE_DB.SILVER.CLAIMS_MU GROUP BY CLAIM_STATUS
UNION ALL SELECT 'AUTH_STATUS', AUTH_STATUS, COUNT(*) FROM HEALTHCARE_DB.SILVER.PRIOR_AUTHORIZATIONS_MU GROUP BY AUTH_STATUS
UNION ALL SELECT 'APPOINTMENT_STATUS', APPOINTMENT_STATUS, COUNT(*) FROM HEALTHCARE_DB.SILVER.APPOINTMENTS_MU GROUP BY APPOINTMENT_STATUS
UNION ALL SELECT 'GENDER', GENDER, COUNT(*) FROM HEALTHCARE_DB.SILVER.PATIENTS_MU GROUP BY GENDER
ORDER BY DOMAIN, VALUE;

-- Verify no negative amounts
SELECT 'CLAIMS' AS TBL, COUNT(*) AS NEGATIVES FROM HEALTHCARE_DB.SILVER.CLAIMS_MU WHERE TOTAL_BILLED_AMOUNT < 0 OR TOTAL_PAID_AMOUNT < 0
UNION ALL SELECT 'CLAIM_LINES', COUNT(*) FROM HEALTHCARE_DB.SILVER.CLAIM_LINES_MU WHERE LINE_BILLED_AMOUNT < 0 OR LINE_PAID_AMOUNT < 0;

-- Verify no orphan FKs
SELECT 'ENCOUNTERS->PATIENTS' AS FK, COUNT(*) AS ORPHANS FROM HEALTHCARE_DB.SILVER.ENCOUNTERS_MU E LEFT JOIN HEALTHCARE_DB.SILVER.PATIENTS_MU P ON E.PATIENT_ID = P.PATIENT_ID WHERE P.PATIENT_ID IS NULL
UNION ALL SELECT 'CLAIMS->PATIENTS', COUNT(*) FROM HEALTHCARE_DB.SILVER.CLAIMS_MU C LEFT JOIN HEALTHCARE_DB.SILVER.PATIENTS_MU P ON C.PATIENT_ID = P.PATIENT_ID WHERE P.PATIENT_ID IS NULL
UNION ALL SELECT 'ENCOUNTERS->PROVIDERS', COUNT(*) FROM HEALTHCARE_DB.SILVER.ENCOUNTERS_MU E LEFT JOIN HEALTHCARE_DB.SILVER.PROVIDERS_MU P ON E.PROVIDER_ID = P.PROVIDER_ID WHERE P.PROVIDER_ID IS NULL;
