-- =====================================================
-- SECTION 4: DATA TRANSFORMATION SILVER -> GOLD LAYER - SINGLE TABLE: PROVIDER_PERFORMANCE_MU
-- ALL providers included, nulls defaulted: date=current_date, number=0, text='Unknown'
-- Columns grouped by business category, no DENIAL_REASON
-- =====================================================

CREATE OR REPLACE TABLE HEALTHCARE_DB.GOLD.FINAL_DASHBOARD_MU AS

WITH dept AS (
    SELECT D.PROVIDER_ID, DEP.DEPARTMENT_NAME
    FROM HEALTHCARE_DB.BRONZE.DOCTORS_MU D
    JOIN HEALTHCARE_DB.SILVER.DEPARTMENTS_MU DEP ON D.DEPARTMENT_ID = DEP.DEPARTMENT_ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY D.PROVIDER_ID ORDER BY D.DOCTOR_ID) = 1
),
appt_agg AS (
    SELECT
        PROVIDER_ID,
        COUNT(*) AS TOTAL_APPOINTMENTS,
        SUM(IFF(APPOINTMENT_STATUS = 'Completed', 1, 0)) AS COMPLETED_APPOINTMENTS,
        SUM(IFF(NO_SHOW_FLAG = TRUE, 1, 0)) AS NO_SHOW_COUNT,
        ROUND(SUM(COPAY_AMOUNT), 2) AS TOTAL_COPAY
    FROM HEALTHCARE_DB.SILVER.APPOINTMENTS_MU
    GROUP BY PROVIDER_ID
),
auth_agg AS (
    SELECT
        PROVIDER_ID,
        COUNT(*) AS TOTAL_AUTHS,
        SUM(IFF(AUTH_STATUS = 'Approved', 1, 0)) AS APPROVED_AUTHS,
        SUM(IFF(AUTH_STATUS = 'Denied', 1, 0)) AS DENIED_AUTHS,
        SUM(IFF(AUTH_STATUS = 'Pending', 1, 0)) AS PENDING_AUTHS,
        ROUND(AVG(DATEDIFF('DAY', REQUEST_DATE, DECISION_DATE)), 1) AS AVG_DECISION_DAYS
    FROM HEALTHCARE_DB.SILVER.PRIOR_AUTHORIZATIONS_MU
    GROUP BY PROVIDER_ID
)

SELECT
    -- 1. Provider Information
    PR.PROVIDER_ID,
    COALESCE(PR.PROVIDER_NAME, 'Unknown') AS PROVIDER_NAME,
    COALESCE(PR.PROVIDER_TYPE, 'Unknown') AS PROVIDER_TYPE,
    COALESCE(PR.SPECIALTY, 'Unknown') AS PROVIDER_SPECIALTY,
    COALESCE(DP.DEPARTMENT_NAME, 'Unknown') AS DEPARTMENT_NAME,

    -- 2. Claim Information
    COALESCE(C.CLAIM_ID, 0) AS CLAIM_ID,
    COALESCE(C.CLAIM_RECEIVED_DATE, CURRENT_DATE()) AS CLAIM_RECEIVED_DATE,
    COALESCE(C.CLAIM_TYPE, 'Unknown') AS CLAIM_TYPE,
    COALESCE(C.CLAIM_STATUS, 'Unknown') AS CLAIM_STATUS,

    -- 3. Financial Metrics
    COALESCE(C.TOTAL_BILLED_AMOUNT, 0) AS TOTAL_BILLED_AMOUNT,
    COALESCE(C.TOTAL_PAID_AMOUNT, 0) AS TOTAL_PAID_AMOUNT,
    COALESCE(C.PATIENT_RESPONSIBILITY_AMOUNT, 0) AS PATIENT_RESPONSIBILITY_AMOUNT,
    COALESCE(AP.TOTAL_COPAY, 0) AS TOTAL_COPAY,

    -- 4. Patient Information
    COALESCE(E.PATIENT_ID, 0) AS PATIENT_ID,
    COALESCE(E.ENCOUNTER_ID, 0) AS ENCOUNTER_ID,
    COALESCE(E.ENCOUNTER_DATE, CURRENT_DATE()) AS ENCOUNTER_DATE,
    COALESCE(E.ENCOUNTER_TYPE, 'Unknown') AS ENCOUNTER_TYPE,

    -- 5. Appointment Metrics
    COALESCE(AP.TOTAL_APPOINTMENTS, 0) AS TOTAL_APPOINTMENTS,
    COALESCE(AP.COMPLETED_APPOINTMENTS, 0) AS COMPLETED_APPOINTMENTS,
    COALESCE(AP.NO_SHOW_COUNT, 0) AS NO_SHOW_COUNT,
    COALESCE(CONCAT(ROUND(COALESCE(AP.NO_SHOW_COUNT,0)*100.0/NULLIF(COALESCE(AP.TOTAL_APPOINTMENTS,0),0),2), '%'), '0%') AS NO_SHOW_RATE,

    -- 6. Authorization Metrics
    COALESCE(AU.TOTAL_AUTHS, 0) AS TOTAL_AUTHS,
    COALESCE(AU.APPROVED_AUTHS, 0) AS APPROVED_AUTHS,
    COALESCE(AU.DENIED_AUTHS, 0) AS DENIED_AUTHS,
    COALESCE(AU.PENDING_AUTHS, 0) AS PENDING_AUTHS,
    COALESCE(CONCAT(ROUND(COALESCE(AU.APPROVED_AUTHS,0)*100.0/NULLIF(COALESCE(AU.TOTAL_AUTHS,0),0),2), '%'), '0%') AS AUTH_APPROVAL_RATE,
    COALESCE(AU.AVG_DECISION_DAYS, 0) AS AVG_DECISION_DAYS,

    -- 7. Reporting Period
    CURRENT_DATE() AS REPORT_DATE,
    MONTH(CURRENT_DATE()) AS REPORT_MONTH,
    YEAR(CURRENT_DATE()) AS REPORT_YEAR

FROM HEALTHCARE_DB.SILVER.PROVIDERS_MU PR
LEFT JOIN dept DP ON PR.PROVIDER_ID = DP.PROVIDER_ID
LEFT JOIN HEALTHCARE_DB.SILVER.ENCOUNTERS_MU E ON PR.PROVIDER_ID = E.PROVIDER_ID
LEFT JOIN HEALTHCARE_DB.SILVER.CLAIMS_MU C ON E.ENCOUNTER_ID = C.ENCOUNTER_ID
LEFT JOIN appt_agg AP ON PR.PROVIDER_ID = AP.PROVIDER_ID
LEFT JOIN auth_agg AU ON PR.PROVIDER_ID = AU.PROVIDER_ID
ORDER BY PR.PROVIDER_ID ASC;

